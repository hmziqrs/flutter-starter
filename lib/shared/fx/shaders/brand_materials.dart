/// The parsed brand materials; each one is one of the sixteen approved looks.
final List<BrandMaterialRecipe> brandMaterials = List<BrandMaterialRecipe>.unmodifiable(
  _brandMaterialPresets.map(BrandMaterialRecipe.fromMap),
);

/// The brand material picked by name: the same name always gets the same one
/// (`materialFor` in `materials.ts`, via the kit's FNV-1a hash + mulberry32).
BrandMaterialRecipe materialFor(String seed) {
  final pick = brandRng(brandStringHash(seed) + 97)();
  return brandMaterials[(pick * brandMaterials.length).floor()];
}

/// Looks up an approved material by id, or null when the id is not one of
/// the sixteen.
BrandMaterialRecipe? brandMaterialById(String id) {
  for (final material in brandMaterials) {
    if (material.id == id) {
      return material;
    }
  }
  return null;
}

/// FNV-1a as in the brand kit's `motion/rings.ts`: a stable 32-bit number
/// from a string, so the same name always picks the same material. Walks
/// UTF-16 code units, matching the kit's `charCodeAt` over code points.
int brandStringHash(String text) {
  var h = 0x811C9DC5;
  for (final unit in text.codeUnits) {
    h ^= unit & 0xFFFF;
    h = (h * 0x01000193) & 0xFFFFFFFF;
  }
  return h;
}

/// mulberry32 as in the brand kit's `motion/rings.ts`: a small seeded random
/// generator producing doubles in 0..1. Bit-level port (all values kept as
/// unsigned 32-bit, the way JavaScript's `>>> 0` leaves them).
double Function() brandRng(int seed) {
  var s = seed & 0xFFFFFFFF;
  return () {
    s = (s + 0x6D2B79F5) & 0xFFFFFFFF;
    var t = _mul32(s ^ (s >>> 15), 1 | s);
    t = ((t + _mul32(t ^ (t >>> 7), 61 | t)) & 0xFFFFFFFF) ^ t;
    return ((t ^ (t >>> 14)) & 0xFFFFFFFF) / 4294967296;
  };
}

int _mul32(int a, int b) => (a * b) & 0xFFFFFFFF;
