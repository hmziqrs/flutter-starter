import 'package:flutter_test/flutter_test.dart';
import 'package:starter/shared/fx/shaders/brand_materials.dart';

void main() {
  group('brandMaterials', () {
    test('carries the sixteen approved ids in the kit order', () {
      expect(brandMaterials.map((material) => material.id), <String>[
        'copper-sweep',
        'hammered-copper',
        'etched-silk',
        'sediment',
        'folded-foil',
        'mineral-fault',
        'lava-fissures',
        'mica-flakes',
        'brushed-alloy',
        'cast-iron',
        'liquid-chrome',
        'hammered-silver',
        'black-ice',
        'carbon-twill',
        'scratched-enamel',
        'black-sweep',
      ]);
    });

    test('every recipe is fully specified and pre-normalized', () {
      expect(brandMaterials.length, 16);
      for (final material in brandMaterials) {
        expect(material.id.isNotEmpty, isTrue, reason: '${material.id} needs an id');
        expect(material.name.isNotEmpty, isTrue);
        expect(material.a.mode, inInclusiveRange(0, 29), reason: material.id);
        expect(material.b.mode, inInclusiveRange(0, 29), reason: material.id);
        expect(material.lightAngle, -0.65, reason: 'the kit lights every material at -0.65');
        expect(material, material.clamped(), reason: material.id);
      }
    });

    test('looks up by id and misses cleanly', () {
      expect(brandMaterialById('copper-sweep')?.name, 'Copper sweep');
      expect(brandMaterialById('teal-tide'), isNull);
    });
  });

  group('materialFor', () {
    // Reference values generated by the brand kit itself
    // (`materialFor` in shaders/materials.ts over motion/rings.ts).
    const expected = <String, String>{
      'hmziq': 'etched-silk',
      'starter': 'sediment',
      'flutter': 'cast-iron',
      'os': 'mineral-fault',
      'copper': 'mineral-fault',
      'test-seed-1': 'brushed-alloy',
      'HMZIQ': 'hammered-copper',
    };

    test('matches the brand kit pick for these seeds', () {
      expected.forEach((seed, id) {
        expect(materialFor(seed).id, id, reason: 'seed "$seed"');
      });
    });

    test('is deterministic for the same seed', () {
      for (final seed in expected.keys) {
        expect(materialFor(seed), materialFor(seed), reason: 'seed "$seed"');
      }
    });

    test('hands out every material across a spread of seeds', () {
      final seen = <String>{
        for (var i = 0; i < 400; i++) materialFor('seed-$i').id,
      };
      expect(seen.length, 16, reason: '400 seeds should reach all sixteen');
    });

    test('the hash and rng port matches the kit bit for bit', () {
      // bun: hash('hmziq') = 3733951930; rng(hash('hmziq') + 97)() = 0.1357…
      expect(brandStringHash('hmziq'), 3733951930);
      expect(brandRng(brandStringHash('hmziq') + 97)(), closeTo(0.13576367683708668, 1e-12));
    });
  });
}
